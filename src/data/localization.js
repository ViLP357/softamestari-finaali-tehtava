export function text(language, key, fallback, values = {}) {
  const template = en.ui[key]
  if (!template || language === 'fi') return fallback
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '')
}

export function localizedRegion(region, language) {
  return language === 'en' ? { ...region, ...en.regions[region.id] } : region
}

export function localizedTask(task, language) {
  if (language === 'fi') return task
  const translation = en.species[task.id]
  if (!translation) throw new Error(`Missing English species translation: ${task.id}`)
  return {
    ...task,
    nameFi: translation.name,
    habitat: translation.habitat,
    ecologicalRole: translation.role,
    question: translation.question,
    choices: translation.choices,
    correctAnswer: translation.choices[task.choices.indexOf(task.correctAnswer)],
    explanation: translation.explanation,
    sourceName: task.sourceName === 'Suomen Lajitietokeskus'
      ? en.ui.sourceSpeciesLaji
      : task.sourceName === 'HELCOM · State of the Baltic Sea'
        ? en.ui.sourceSpeciesStatus
        : task.sourceName,
    photo: task.photo ? { ...task.photo, alt: translation.name } : undefined,
  }
}

export function localizedAction(action, language) {
  return language === 'en' ? { ...action, ...en.actions[action.id] } : action
}

export function roundName(round, language) {
  return language === 'en' ? en.rounds[['plants', 'fish', 'life'][round]].name : ['Kasvit ja levät', 'Kalojen ravintoverkot', 'Muut eliöt ja ympäristö'][round]
}

export function roundDescription(round, language) {
  return language === 'en' ? en.rounds[['plants', 'fish', 'life'][round]].description : [
    'Tutki vedenalaisia kasveja ja leviä sekä niiden tarjoamia elinympäristöjä.',
    'Selvitä, miten kalat liittyvät Itämeren ravintoverkkoihin ja rannikon elinympäristöihin.',
    'Tunnista merieläimiä ja ympäristöilmiöitä, jotka vaikuttavat Itämeren elämään.',
  ][round]
}
